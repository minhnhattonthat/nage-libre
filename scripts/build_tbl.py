"""Generate nage.tbl from font/glyphs.txt.

glyphs.txt rows: `CODE[/STEP] chars` — CODE = hex code of the first glyph (sheet row label),
STEP = code increment per char (default 2 = full-width 16x16; 1 for half-width).
＿ = empty slot (no entry), 〓 = unreadable (no entry, listed on stdout).
Repeated glyphs get a variation selector so codes stay unique (see entries()).

    python -I scripts/build_tbl.py            # writes nage.tbl
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rom

SRC = os.path.join(rom.ROOT, "font", "glyphs.txt")
OUT = os.path.join(rom.ROOT, "nage.tbl")
HEADER = """# Nage Libre table — GENERATED by scripts/build_tbl.py from font/glyphs.txt, do not edit.
# Codes are 16-bit LE glyph indices (font offset 0x28000 + code*0x20), written in ROM byte order.
# Strings end with FFFF. No in-string control codes; lines wrap by width, padded with the blank glyph 03FE.
FFFF=<END>!
FE03=　
"""


def _rows(text):
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        head, chars = line.split(" ", 1)
        code, _, step = head.partition("/")
        yield int(code, 16), int(step or "2"), chars


def entries(text):
    """Table lines. A glyph seen again (variant form in the font) gets U+FE01, U+FE02, ... appended:
    invisible when reading, but unique, so every code round-trips."""
    out, seen = [], {}
    for code, step, chars in _rows(text):
        for i, ch in enumerate(chars):
            if ch not in "＿〓":
                c = code + i * step
                n = seen.get(ch, 0)
                seen[ch] = n + 1
                out.append(f"{c & 0xFF:02X}{c >> 8:02X}={ch}{chr(0xFE00 + n) if n else ''}")
    return out


def unknown(text):
    return [code + i * step for code, step, chars in _rows(text) for i, ch in enumerate(chars) if ch == "〓"]


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")          # console is cp1252; -I ignores PYTHONIOENCODING
    with open(SRC, encoding="utf-8") as f:
        text = f.read()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "\n".join(entries(text)) + "\n")
    unk = unknown(text)
    print(f"wrote {OUT}: {len(entries(text))} glyphs; unreadable: {' '.join(f'{c:04X}' for c in unk) or 'none'}")
